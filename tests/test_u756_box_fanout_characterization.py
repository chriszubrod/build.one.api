class Recorder:
    def __init__(self):
        self.calls: list = []

    def rec(self, name, *args, **kwargs):
        self.calls.append((name, args, tuple(sorted(kwargs.items()))))


def _make_folder_cls(rec, mappings, *, init_raises=None):
    class FakeFolderService:
        def __init__(self):
            rec.rec("BoxProjectFolderService()")
            if init_raises:
                raise init_raises

        def read_mapping_by_project_id_and_class(self, project_id, doc_class):
            rec.rec("folder.read_mapping_by_project_id_and_class", project_id, doc_class)
            return mappings.get(project_id)

    return FakeFolderService


def _make_outbox_cls(rec, *, raises=None):
    class FakeOutbox:
        def __init__(self):
            rec.rec("BoxOutboxService()")

        def enqueue_box_upload(self, **kwargs):
            rec.rec("outbox.enqueue_box_upload", **kwargs)
            if raises:
                raise raises

        def enqueue_box_excel(self, **kwargs):
            rec.rec("outbox.enqueue_box_excel", **kwargs)
            if raises:
                raise raises

        def enqueue_box_excel_draw_stamp(self, **kwargs):
            rec.rec("outbox.enqueue_box_excel_draw_stamp", **kwargs)
            if raises:
                raise raises

    return FakeOutbox


def _make_workbook_cls(rec, mappings, *, raises=None):
    class FakeWorkbook:
        def __init__(self):
            rec.rec("BoxProjectWorkbookService()")

        def read_by_project_id(self, project_id):
            rec.rec("workbook.read_by_project_id", project_id)
            if raises:
                raise raises
            return mappings.get(project_id)

    return FakeWorkbook


class FakeLinkService:
    """Answers every read_by_*_line_item_id spelling; links keyed by line public_id."""

    def __init__(self, rec, links, *, raise_for=()):
        self._rec, self._links, self._raise_for = rec, links, set(raise_for)

    def _read(self, name, **kwargs):
        self._rec.rec(name, **kwargs)
        (pid,) = kwargs.values()
        if pid in self._raise_for:
            raise RuntimeError(f"link-boom {pid}")
        return self._links.get(pid)

    def read_by_bill_line_item_id(self, **kw):
        return self._read("link.read_by_bill_line_item_id", **kw)

    def read_by_expense_line_item_id(self, **kw):
        return self._read("link.read_by_expense_line_item_id", **kw)

    def read_by_bill_credit_line_item_id(self, **kw):
        return self._read("link.read_by_bill_credit_line_item_id", **kw)


class FakeAttachmentService:
    def __init__(self, rec, attachments, *, raise_for=()):
        self._rec, self._att, self._raise_for = rec, attachments, set(raise_for)

    def read_by_id(self, id):
        self._rec.rec("attachment.read_by_id", id=id)
        if id in self._raise_for:
            raise RuntimeError(f"att-boom {id}")
        return self._att.get(id)


class FakeReadById:
    def __init__(self, rec, name, rows, *, raises=None, raise_for=()):
        self._rec, self._name, self._rows, self._raises = rec, name, rows, raises
        self._raise_for = set(raise_for)

    def read_by_id(self, id):
        self._rec.rec(f"{self._name}.read_by_id", id=id)
        if self._raises:
            raise self._raises
        if id in self._raise_for:
            raise RuntimeError(f"{self._name}-boom {id}")
        return self._rows.get(id)



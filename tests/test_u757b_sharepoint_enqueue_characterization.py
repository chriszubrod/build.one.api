def _ordered(obj):
    """Dicts -> [key, value] pair lists (key order is part of the contract)."""
    if isinstance(obj, dict):
        return [[k, _ordered(v)] for k, v in obj.items()]
    if isinstance(obj, (list, tuple)):
        return [_ordered(v) for v in obj]
    return obj


@contextlib.contextmanager
def _capturing():
    handler = _ListHandler()
    saved = []
    for name in _LOGGERS:
        lg = logging.getLogger(name)
        saved.append((lg, lg.level))
        lg.setLevel(logging.DEBUG)
        lg.addHandler(handler)
    out = io.StringIO()
    try:
        with contextlib.redirect_stdout(out):
            yield handler, out
    finally:
        for lg, level in saved:
            lg.removeHandler(handler)
            lg.setLevel(level)


def _pack(handler, out, rec, result):
    return {
        "result": _ordered(result),
        "calls": json.loads(json.dumps(rec.calls, default=str)),
        "logs": [
            [r.name, r.levelname, r.getMessage(), bool(r.exc_info)]
            for r in handler.records
            if r.name in _LOGGERS
        ],
        "stdout": out.getvalue(),
    }


def _run_receipts(cfg):
    rec = Recorder()
    svc = object.__new__(ExpenseService)
    svc.vendor_service = FakeReadById(rec, "vendor", cfg.get("vendors", _R_VENDORS))
    svc.project_service = FakeReadById(rec, "project", cfg.get("projects", _R_PROJECTS))
    svc.sub_cost_code_service = FakeSccService(rec, _R_SCCS, holding=cfg.get("holding", ()))
    svc.attachment_service = FakeReadById(rec, "attachment", _R_ATTS, raise_for=cfg.get("att_raise", ()))
    svc._expense_line_item_attachment_service = FakeLinkService(rec, _R_LINKS, raise_for=cfg.get("link_raise", ()))
    svc._expense_line_item_service = FakeExpenseLineItemService(
        rec, cfg.get("full_lines", cfg["lines"]), raises=cfg.get("eli_raises"),
    )
    svc._driveitem_service = FakeDriveItemService(rec, cfg.get("create", {}))
    root_l, child_l = _make_listers(rec, cfg.get("tree", _R_TREE), cfg.get("list_fail", ()))

    patches = [
        patch(_OUTBOX, _make_outbox_cls(rec, cfg.get("plan", {}))),
        patch(f"{_EXPENSE_MOD}.AzureBlobStorage", _make_storage_cls(
            rec, init_raises=cfg.get("storage_init_raises"),
            download_raise_for=cfg.get("download_raise_for", ()))),
        patch(f"{_EXPENSE_MOD}.MsDriveService", _make_drive_service_cls(
            rec, cfg.get("drives", [_drive()]), raises=cfg.get("drives_raise"))),
        patch(f"{_EXPENSE_MOD}.list_drive_root_children", root_l),
        patch(f"{_EXPENSE_MOD}.list_drive_item_children", child_l),
    ]
    with _capturing() as (handler, out):
        for p in patches:
            p.start()
        try:
            result = svc._upload_to_general_receipts_folder(cfg.get("entity", _expense()), cfg["lines"])
        finally:
            for p in reversed(patches):
                p.stop()
    return _pack(handler, out, rec, result)



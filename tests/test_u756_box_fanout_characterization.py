def _bill():
    return SimpleNamespace(
        id=1, public_id="bill-pub", vendor_id=55, bill_number="INV-9",
        bill_date="2026-10-02T00:00:00", total_amount=Decimal("1234.5"),
    )


def _bill_service(rec, *, link_raise=(), att_raise=(), vendor_rows=None, project_rows=None,
                  vendor_raises=None, filename_override=_REAL,
                  project_raise_for=(), filename_raise_for=()):
    svc = object.__new__(BillService)
    svc.bill_line_item_attachment_service = FakeLinkService(rec, _LINKS, raise_for=link_raise)
    svc.attachment_service = FakeAttachmentService(rec, _ATTS, raise_for=att_raise)
    svc.vendor_service = FakeReadById(
        rec, "vendor",
        vendor_rows if vendor_rows is not None else {55: SimpleNamespace(abbreviation="ACME", name="Acme")},
        raises=vendor_raises,
    )
    svc.project_service = FakeReadById(
        rec, "project",
        project_rows if project_rows is not None else {
            "10": SimpleNamespace(abbreviation="P10", name="Proj 10"),
            "30": SimpleNamespace(abbreviation=None, name="Proj/30"),
        },
        raise_for=project_raise_for,
    )
    svc.sub_cost_code_service = FakeReadById(
        rec, "scc", {"7001": SimpleNamespace(number="01.10", name="Framing"),
                     "7002": SimpleNamespace(number="01.20", name="Drywall")},
    )
    real = BillService._build_module_filename.__get__(svc)

    def _recording_build(**kwargs):
        rec.rec("bill._build_module_filename",
                line=kwargs["line_item"].public_id,
                vendor=getattr(kwargs["vendor"], "abbreviation", None),
                project=getattr(kwargs["project"], "name", None),
                count=kwargs["bill_line_items_count"],
                attachment=kwargs["attachment"].id)
        if kwargs["line_item"].public_id in filename_raise_for:
            raise RuntimeError(f"fname-boom {kwargs['line_item'].public_id}")
        if filename_override is not _REAL:
            return filename_override
        return real(**kwargs)

    svc._build_module_filename = _recording_build
    return svc



def _ordered(obj):
    """Dicts -> [key, value] pair lists (key order is part of the contract)."""
    if isinstance(obj, dict):
        return [[k, _ordered(v)] for k, v in obj.items()]
    if isinstance(obj, (list, tuple)):
        return [_ordered(v) for v in obj]
    return obj


def _capture(caplog, capsys, rec, result):
    out = capsys.readouterr().out
    logs = [
        [r.name, r.levelname, r.getMessage(), bool(r.exc_info)]
        for r in caplog.records
        if r.name in _LOGGERS
    ]
    return {
        "result": _ordered(result),
        "calls": json.loads(json.dumps(rec.calls, default=str)),
        "logs": logs,
        "stdout": out,
    }


def _run_entity(entity, cfg, caplog, capsys):
    rec = Recorder()
    mod = {"bill": _BILL_MOD, "credit": _CREDIT_MOD, "expense": _EXPENSE_MOD}[entity]

    def _issue(**kwargs):
        rec.rec("record_project_mapping_missing_ms_issue", **kwargs)

    caplog.clear()
    capsys.readouterr()
    patches = [
        patch(f"{mod}._record_project_mapping_missing_ms_issue", _issue),
        patch(_OUTBOX, _make_outbox_cls(rec, cfg.get("plan", _DEFAULT_PLAN))),
    ]
    if entity != "credit":
        patches.append(patch(
            f"{mod}.AzureBlobStorage",
            _make_storage_cls(rec, init_raises=cfg.get("storage_init_raises"),
                              download_raise_for=cfg.get("download_raise_for", ())),
        ))
    for p in patches:
        p.start()
    try:
        lines = cfg["lines"]
        if entity == "bill":
            svc = _bill_service(rec, cfg)
            result = svc._upload_attachments_to_module_folder(
                cfg.get("entity", _bill()), lines, cfg.get("project_id", 10),
                bill_line_items_count=cfg.get("count", 1),
            )
        elif entity == "credit":
            svc = _credit_service(rec, cfg)
            result = svc._upload_attachments_to_module_folder(
                bill_credit=cfg.get("entity", _credit()), line_items=lines,
                project_id=cfg.get("project_id", 10),
            )
        else:
            svc = _expense_service(rec, cfg)
            result = svc._upload_attachments_to_module_folder(
                cfg.get("entity", _expense()), lines, cfg.get("project_id", 10),
                expense_line_items_count=cfg.get("count", 1),
            )
    finally:
        for p in reversed(patches):
            p.stop()
    return _capture(caplog, capsys, rec, result)



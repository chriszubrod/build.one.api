class Recorder:
    def __init__(self):
        self.calls: list = []

    def rec(self, name, *args, **kwargs):
        self.calls.append([name, list(args), sorted([k, v] for k, v in kwargs.items())])


class _ListHandler(logging.Handler):
    def __init__(self):
        super().__init__(level=logging.DEBUG)
        self.records: list = []

    def emit(self, record):
        self.records.append(record)


def _make_outbox_cls(rec, plan):
    """plan: attachment_id -> 'pending' | 'done' | None (refused) | 'raise'."""

    class FakeOutbox:
        def __init__(self):
            rec.rec("MsOutboxService()")

        def enqueue_sharepoint_upload(self, **kwargs):
            rec.rec("outbox.enqueue_sharepoint_upload", **kwargs)
            status = plan.get(kwargs["attachment_id"], "pending")
            if status == "raise":
                raise RuntimeError(f"enqueue-boom {kwargs['attachment_id']}")
            if status is None:
                return None
            return SimpleNamespace(public_id=f"ob-{kwargs['attachment_id']}", status=status)

    return FakeOutbox


class FakeReadById:
    def __init__(self, rec, name, rows, *, raise_for=()):
        self._rec, self._name, self._rows, self._raise_for = rec, name, rows, set(raise_for)


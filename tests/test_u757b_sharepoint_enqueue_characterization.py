"""U-757b — characterization goldens for the two remaining hand-rolled SharePoint enqueue loops.

Frozen against the PRE-refactor code (origin/master 60fb58ad) and must stay
green, UNCHANGED, after ``ExpenseService._upload_to_general_receipts_folder``
and ``InvoiceService._upload_to_sharepoint`` (line loop + packet loop) moved
onto ``shared.completion.sharepoint_fanout.enqueue_attachment_file``.

Every scenario drives the private method with recording fakes for every
collaborator and compares, to a golden literal:

- the FULL return dict, key order included (``_ordered``),
- the full call trace (every collaborator call + args, in order) — the exact
  SharePoint FILENAME / content_type / parent / attachment_id of every enqueue
  lives here (the outbox idempotency guard keys on filename),
- every log record (logger name, level, message, has-exc_info),
- everything written to stdout.

The receipts scenarios use the REAL ``_navigate_to_folder`` /
``_get_or_create_subfolder`` so the known U-768 defect (a newly CREATED
year/month folder is read as ``create_result["item"]["id"]`` while
``_format_drive_item`` emits ``item_id`` -> KeyError -> outer error) is pinned
as-is; it is deliberately NOT fixed here.

Nothing here touches a DB, Graph, blob storage or the network.
"""


def _make_listers(rec, tree, fail_for=()):
    fail_for = set(fail_for)

    def list_drive_root_children(drive_id):
        rec.rec("list_drive_root_children", drive_id)
        if "__root__" in fail_for:
            return {"status_code": 500, "message": "root-down"}
        return {"status_code": 200, "items": list(tree.get("__root__", []))}

    def list_drive_item_children(drive_id, item_id):
        rec.rec("list_drive_item_children", drive_id, item_id)
        if item_id in fail_for:
            return {"status_code": 404, "message": f"gone {item_id}"}
        return {"status_code": 200, "items": list(tree.get(item_id, []))}

    return list_drive_root_children, list_drive_item_children



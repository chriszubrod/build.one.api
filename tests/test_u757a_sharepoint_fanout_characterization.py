class Recorder:
    def __init__(self):
        self.calls: list = []

    def rec(self, name, *args, **kwargs):
        self.calls.append([name, list(args), sorted([k, v] for k, v in kwargs.items())])


class FakeModuleService:
    def __init__(self, rec, by_name, all_modules=(), *, raises=None):
        self._rec, self._by_name, self._all, self._raises = rec, by_name, list(all_modules), raises

    def read_by_name(self, name):
        self._rec.rec("module.read_by_name", name)
        if self._raises:
            raise self._raises
        return self._by_name.get(name)

    def read_all(self):
        self._rec.rec("module.read_all")
        return list(self._all)


class FakeConnector:
    def __init__(self, rec, folders):
        self._rec, self._folders = rec, folders

    def get_folder_for_module(self, project_id, module_id):
        self._rec.rec("connector.get_folder_for_module", project_id=project_id, module_id=module_id)
        return self._folders.get(project_id)


class FakeReadById:
    def __init__(self, rec, name, rows, *, raise_for=()):
        self._rec, self._name, self._rows, self._raise_for = rec, name, rows, set(raise_for)

    def read_by_id(self, id):
        self._rec.rec(f"{self._name}.read_by_id", id=id)
        if id in self._raise_for:
            raise RuntimeError(f"{self._name}-boom {id}")
        return self._rows.get(id)


class FakeDriveRepo(FakeReadById):
    def read_by_id(self, id):  # positional, like MsDriveRepository
        self._rec.rec("drive.read_by_id", id)
        return self._rows.get(id)


class FakeSccService(FakeReadById):
    def __init__(self, rec, rows, holding=()):
        super().__init__(rec, "scc", rows)
        self._holding = set(holding)

    def is_holding_code(self, sid):
        self._rec.rec("scc.is_holding_code", sid)
        return sid in self._holding


class FakeLinkService:
    """Answers every read_by_*_line_item_id spelling; links keyed by line public_id."""

    def __init__(self, rec, links, *, raise_for=()):
        self._rec, self._links, self._raise_for = rec, links, set(raise_for)

    def _read(self, name, **kwargs):
        self._rec.rec(name, **kwargs)
        (pid,) = kwargs.values()
        if pid in self._raise_for:
            raise RuntimeError(f"link-boom {pid}")
        return self._links.get(pid)

    def read_by_bill_line_item_id(self, **kw):
        return self._read("link.read_by_bill_line_item_id", **kw)

    def read_by_expense_line_item_id(self, **kw):
        return self._read("link.read_by_expense_line_item_id", **kw)

    def read_by_bill_credit_line_item_id(self, **kw):
        return self._read("link.read_by_bill_credit_line_item_id", **kw)


class FakeExpenseLineItemService:
    def __init__(self, rec, full_lines, *, raises=None):
        self._rec, self._full, self._raises = rec, full_lines, raises


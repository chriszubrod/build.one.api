def _normalise(tr):
    return {
        "result": tr["result"],
        "calls": [list(c[:1]) + [list(c[1]), [list(kv) for kv in c[2]]] for c in tr["calls"]],
        "logs": [list(l) for l in tr["logs"]],
    }



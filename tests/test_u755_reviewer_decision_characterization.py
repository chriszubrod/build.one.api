def _run(entity, path, **over):
    cfg = ENT[entity]
    d = _defaults(entity, path)
    kwargs_over = over.pop("kwargs", {})
    d.update(over)
    rec: list = []
    counter = itertools.count(1)

    @contextmanager
    def fake_get_connection(*a, **kw):
        conn = _Conn(next(counter))
        rec.append(("get_connection.enter", conn._tag))
        try:
            yield conn
        except BaseException as e:
            rec.append(("get_connection.exit", conn._tag, type(e).__name__))
            raise
        else:
            rec.append(("get_connection.exit", conn._tag, None))

    lines = d["lines"]
    line_proxy = _Proxy(rec, "lines", {
        cfg["read_lines"]: lambda **kw: list(lines),
        cfg["count"]: (lambda *a, **kw: len(lines)) if d["count"] is None else d["count"],
        cfg["read_tx"]: (lambda **kw: list(lines)) if d["lines_tx"] is None else d["lines_tx"],
        "update_coding_in_transaction": d["update"],
    })
    recip_proxy = _Proxy(rec, "recipients", {cfg["recip"]: d["envelope"]})
    status_proxy = _Proxy(rec, "statuses", {
        "read_all": lambda: list(d["read_all"]),
        "read_by_id": lambda id: STATUSES.get(id),
        "get_approved_status": d["approved"],
        "get_declined_statuses": lambda: list(d["declined"]),
    })
    review_proxy = _Proxy(rec, "reviews", {
        cfg["lock"]: d["current"],
        "read_by_idempotency_key": list(d["idem"]),
        "create": d["create"],
    })
    scc_proxy = _Proxy(rec, "scc", {
        "read_by_public_id": d["scc"],
        "is_holding_code": lambda sid: sid in d["holding_ids"],
    })

    def fake_bind(**kw):
        rec.append(("bind_reviewer_reply_to_review_thread", _norm(kw)))
        if isinstance(d["provenance"], BaseException):
            raise d["provenance"]
        return d["provenance"]

    def fake_act_as(**kw):
        rec.append(("assert_may_act_as", _norm(kw)))
        if isinstance(d["delegated"], BaseException):
            raise d["delegated"]
        return d["delegated"]

    import importlib

    svc_mod = importlib.import_module(cfg["mod"])
    svc = getattr(svc_mod, cfg["cls"])(repo=MagicMock())

    def fake_read(**kw):
        rec.append(("service.read_by_public_id", _norm(kw)))
        return d["parent"]

    logs: list = []

    class _H(logging.Handler):
        def emit(self, r):
            if r.name.startswith("entities.") or r.name.startswith("shared.") or r.name.startswith("integrations."):
                logs.append((r.name, r.levelname, r.getMessage()))

    handler = _H(level=logging.DEBUG)
    root = logging.getLogger()
    old_level = root.level
    root.addHandler(handler)
    root.setLevel(logging.DEBUG)
    try:
        with ExitStack() as st:
            st.enter_context(patch(f"{cfg['mod']}.get_connection", fake_get_connection))
            st.enter_context(patch(f"{cfg['mod']}.SubCostCodeService", side_effect=_factory(rec, "SubCostCodeService", scc_proxy)))
            st.enter_context(patch(f"{cfg['mod']}.assert_may_act_as", fake_act_as))
            st.enter_context(patch(cfg["line_cls"], side_effect=_factory(rec, "LineItemService", line_proxy)))
            st.enter_context(patch("entities.review.business.recipient_service.ReviewRecipientService", side_effect=_factory(rec, "ReviewRecipientService", recip_proxy)))
            st.enter_context(patch("entities.review_status.business.service.ReviewStatusService", side_effect=_factory(rec, "ReviewStatusService", status_proxy)))
            st.enter_context(patch("entities.review.persistence.repo.ReviewRepository", side_effect=_factory(rec, "ReviewRepository", review_proxy)))
            st.enter_context(patch("shared.authz.provenance.bind_reviewer_reply_to_review_thread", fake_bind))
            st.enter_context(patch.object(svc, "read_by_public_id", fake_read))
            st.enter_context(actor_context(ACTOR_ID, False))
            if path == "A":
                kwargs = {
                    cfg["pid_kw"]: PID,
                    "decision": "approved",
                    "reviewer_email": "pm@example.COM",
                    "sub_cost_code_public_id": "SCC-PID",
                    "description": "New desc",
                    "raw_reply_text": "  Looks good  ",
                    "reviewer_email_message_public_id": "MSG-PID",
                }
                kwargs.update(kwargs_over)
                fn = svc.apply_reviewer_decision
            else:
                kwargs = {
                    cfg["pid_kw"]: PID,
                    "decision": "approved",
                    "sub_cost_code_public_id": "SCC-PID",
                    "description": "New desc",
                    "idempotency_key": "IDEM-1",
                    "line_row_version": "RV1",
                    "expected_review_public_id": "CUR-1",
                    "caller_user_id": REVIEWER_ID,
                }
                kwargs.update(kwargs_over)
                fn = svc.apply_transactional_reviewer_decision
            try:
                outcome = {"returned": _norm(fn(**kwargs))}
            except BaseException as e:  # noqa: BLE001 — characterization
                outcome = {
                    "raised": type(e).__name__,
                    "str": str(e),
                    "error_code": getattr(e, "error_code", None),
                    "status_code": getattr(e, "status_code", None),
                    "detail": getattr(e, "detail", None),
                }
    finally:
        root.removeHandler(handler)
        root.setLevel(old_level)
    return {"calls": [list(c) for c in rec], "outcome": outcome, "logs": [list(l) for l in logs]}



def _norm(x):
    if hasattr(x, "_tag"):
        return f"<{x._tag}>"
    if isinstance(x, (list, tuple)):
        return [_norm(i) for i in x]
    if isinstance(x, dict):
        return {k: _norm(v) for k, v in sorted(x.items())}
    if isinstance(x, BaseException):
        return f"{type(x).__name__}({x})"
    return x


class _Conn:
    def __init__(self, n):
        self._tag = f"conn{n}"


class _Proxy:
    """Records every method call; behaviour per method: value | exception | callable |
    list (a SEQUENCE: one item per call — wrap a list-valued return in a lambda)."""

    def __init__(self, rec, name, beh):
        self._rec, self._name, self._beh = rec, name, beh

    def __getattr__(self, m):
        if m.startswith("_"):
            raise AttributeError(m)

        def call(*a, **kw):
            self._rec.append((f"{self._name}.{m}", _norm(list(a)), _norm(kw)))
            b = self._beh.get(m)
            if isinstance(b, list):
                b = b.pop(0) if b else None
            if callable(b) and not isinstance(b, type):
                b = b(*a, **kw)
            if isinstance(b, BaseException):
                raise b
            return b

        return call


def _factory(rec, name, proxy):
    def make(*a, **kw):
        rec.append((f"new {name}", _norm(list(a)), _norm(kw)))
        return proxy

    return make


